/**
 * The product catalogue: one row per product, as a synonym set.
 *
 *   [name, category, aka, sub?, brands?]
 *
 * aka     Names that mean exactly this product: English, Hindi, Tamil, Telugu,
 *         Kannada, Malayalam and common misspellings. The FIRST one is the
 *         canonical tag. Any of them in a basket line is searched, matched,
 *         and saved in history as the canonical tag, so "kismis", "kishmish"
 *         and "dry grapes" are one product ("raisins") with one price history.
 * sub     Narrower names ("salted butter", "mango juice"). They identify the
 *         product (and its category) but are kept as typed, because folding
 *         them would lose what the user asked for.
 * brands  Brand facets ("harpic", "dalda"). Never product tags: a brand query
 *         stays brand-specific; the brand is reported beside the product.
 *
 * Data notes (changes from the source list, so one name means one product):
 *   - "chickpeas" and "chole" belong to Kabuli chana only, not to Chana.
 *   - "kala namak" and "black salt" belong to Black salt only, not Rock salt.
 *   - "gud powder" belongs to Jaggery powder only, not to Jaggery.
 *   - "instant noodles" is its own product, not a Noodles tag.
 *   - The two Butter rows are merged.
 *   - Horlicks / Bournvita / Complan / Boost are brands of "health drink";
 *     Kurkure of "corn snacks"; Harpic, Surf, Dalda, Milkmaid, Nutella,
 *     Duracell and Marie Gold are brand facets of their products.
 *   - Every aka name is the same form as the canonical one: "turmeric
 *     powder" is a sub-name of Turmeric, not an aka, or "turmeric powder"
 *     would be searched as plain "turmeric". "methi" and "sarson" are
 *     sub-names too (they are as often the leaves / greens).
 *   - Words too generic to stand for one product are left out: cereal,
 *     sauce, powder, gum, sweets, dental, pearls (they would hijack
 *     "turmeric powder" or "chilli sauce").
 */
