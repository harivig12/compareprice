#!/usr/bin/env node
/**
 * Generate real webcmd adapters from src/extract/*.js into ~/.webcmd/clis/.
 *
 * The extraction logic has exactly one home — the extractor modules. Adapters
 * may only import from `@agentrhq/webcmd/*`, so they can't require our source;
 * generating them keeps the two surfaces from drifting instead of maintaining
 * the same selectors twice.
 *
 *   node scripts/build-adapters.js            # all implemented sites
 *   node scripts/build-adapters.js blinkit    # just one
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

import { EXTRACTORS } from '../src/extract/index.js';

const CLIS_DIR = join(homedir(), '.webcmd', 'clis');

// Instamart's extractor is a stub — generating an adapter for it would install
// a command that always fails.
const IMPLEMENTED = ['blinkit', 'zepto', 'bigbasket', 'amazon'];

const only = process.argv.slice(2).filter((a) => !a.startsWith('-'));
const sites = only.length > 0 ? only : IMPLEMENTED;

function adapterSource(site, ex) {
  // The extractor's expressions are plain strings evaluated in page context,
  // so they embed directly. JSON.stringify handles escaping.
  return `// GENERATED by scripts/build-adapters.js — edit src/extract/${site}.js instead.
//
// ${ex.label} search adapter.
// Strategy: UI — depends on the rendered page and on the delivery location
// held in the webcmd browser profile. siteSession 'persistent' keeps that
// location alive across commands.

import { cli, Strategy } from '@agentrhq/webcmd/registry';
import { EmptyResultError, CommandExecutionError } from '@agentrhq/webcmd/errors';

const READY = ${JSON.stringify(ex.readyExpression)};
const EXTRACT = ${JSON.stringify(ex.extractExpression)};

const searchUrl = (query) => ${JSON.stringify(ex.searchUrl('__Q__'))}.replace(
  '__Q__',
  encodeURIComponent(query),
);

cli({
  site: '${site}',
  name: 'search',
  description: 'Search ${ex.label} and return products with pack size, price, MRP and stock.',
  access: 'read',
  example: 'webcmd ${site} search "amul butter 500g" -f json',
  domain: '${site}',
  strategy: Strategy.UI,
  browser: true,
  siteSession: 'persistent',
  args: [
    { name: 'query', type: 'string', required: true, help: 'What to search for' },
    { name: 'limit', type: 'int', default: 30, help: 'Max rows to return' },
  ],
  tags: ['search'],
  columns: ['name', 'packSize', 'packUnit', 'price', 'mrp', 'inStock', 'url'],
  func: async (page, kwargs) => {
    const query = String(kwargs.query || '').trim();
    if (!query) throw new EmptyResultError('query is empty');

    await page.goto(searchUrl(query), { waitUntil: 'load', settleMs: 1500 });

    // Poll until the results actually render. These storefronts hydrate after
    // load, so a bare goto() returns an empty grid.
    let ready = false;
    for (let i = 0; i < 24; i++) {
      try {
        if (await page.evaluate(READY)) { ready = true; break; }
      } catch { /* page still navigating */ }
      await new Promise((r) => setTimeout(r, 700));
    }
    if (!ready) {
      throw new CommandExecutionError(
        '${ex.label} results never rendered — check the delivery location is set in the webcmd profile',
      );
    }

    // These storefronts are SPAs that can navigate again after first render
    // (Zepto in particular), which destroys the execution context mid-call.
    // Retry the extraction rather than failing the whole search.
    let out = null;
    let lastErr = null;
    for (let i = 0; i < 4; i++) {
      try {
        out = await page.evaluate(EXTRACT);
        if (out && !out.error) break;
        lastErr = out && out.error ? new Error(out.error) : null;
      } catch (err) {
        lastErr = err;
        // Context destroyed — let the page settle and try again.
      }
      await new Promise((r) => setTimeout(r, 1500));
    }

    if (out && out.error) {
      throw new CommandExecutionError('${ex.label} extraction failed: ' + out.error);
    }
    if (!out) {
      throw new CommandExecutionError(
        '${ex.label} extraction failed: ' + (lastErr ? lastErr.message : 'no result'),
      );
    }

    const rows = (out && out.rows) || [];
    if (rows.length === 0) {
      throw new EmptyResultError('no products found for "' + query + '" on ${ex.label}');
    }

    const limit = Number(kwargs.limit) > 0 ? Number(kwargs.limit) : 30;
    return rows.slice(0, limit).map((r) => ({
      name: String(r.name),
      packSize: r.packSize == null ? null : Number(r.packSize),
      packUnit: r.packUnit == null ? null : String(r.packUnit),
      price: Number(r.price),
      mrp: r.mrp == null ? null : Number(r.mrp),
      inStock: Boolean(r.inStock),
      url: String(r.url),
    }));
  },
});
`;
}

let written = 0;
for (const site of sites) {
  const ex = EXTRACTORS[site];
  if (!ex) {
    console.error(`✖ no extractor for "${site}"`);
    process.exitCode = 1;
    continue;
  }
  if (!ex.extractExpression || ex.extractExpression.includes('not_implemented')) {
    console.log(`- skipped ${site} (extractor is a stub)`);
    continue;
  }
  const dir = join(CLIS_DIR, site);
  mkdirSync(dir, { recursive: true });
  const file = join(dir, 'search.js');
  writeFileSync(file, adapterSource(site, ex), 'utf8');
  console.log(`✔ ${file}`);
  written++;
}

console.log(`\n${written} adapter(s) written. Verify with:`);
console.log(`  webcmd list -f json`);
for (const s of sites) console.log(`  webcmd ${s} search "amul butter 500g" -f json`);
